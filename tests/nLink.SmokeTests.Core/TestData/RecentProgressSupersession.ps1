function Verify([string]$case,[object[]]$inputEvents,$evidence,[bool]$expected,[switch]$Gui) {
    $flat=& $script:FileTransferFallbackFrontierRecentProgressGraceLegacyCorrelation -Events $inputEvents -SnapshotEvidence $evidence
    $index=New-FileTransferFallbackFrontierGraceCorrelationIndex -Events $inputEvents -SnapshotEvidence $evidence
    $indexed=Get-FileTransferFallbackFrontierRecentProgressGraceRecheckCorrelation -Events $inputEvents -Index $index
    $wanted=if($expected){"2/$($holds.Count)/1/0/1/0"}else{"2/$($holds.Count)/1/0/0/1"}
    foreach($r in @($flat,$indexed)) {
        Check ((Counts $r) -ceq $wanted) "$case expected $wanted got $(Counts $r): $($r.CandidateRecords[0].SupersessionFailureReason)"
        Check (-not $r.CandidateRecords[0].Recovered -and $null -eq $r.CandidateRecords[0].RecoveryEvent) "$case manufactured repair recovery"
    }
    if($Gui) {
        $guiLines=@(foreach($e in @($inputEvents | Sort-Object Sequence,LineNumber)) {
            '[2026-09-23 16:48:34Z] [INFO] [Unit] '+(@($e.Fields.Keys | Sort-Object | ForEach-Object {"$_=$($e.Fields[$_])"}) -join '; ')+
                '; gui_evidence_sequence='+$e.Sequence
        })
        $g=Get-TunaGuiFallbackFrontierRecentProgressGraceRecheckFailure -Lines $guiLines -SnapshotEvidence $evidence
        Check ($g.Unresolved -eq (-not $expected) -and $g.SupersededCount -eq [int]$expected -and $g.AccountingVersion -eq 2) "$case GUI parity"
    }
    $script:tested++
    Write-Output "pass $case"
}
