function Copy-Value($value) {
    $copy=[Management.Automation.PSSerializer]::Deserialize([Management.Automation.PSSerializer]::Serialize($value,64))
    foreach($item in @($copy)) {
        if($null -ne $item.PSObject.Properties['TimestampUtc'] -and $null -ne $item.TimestampUtc) {
            $item.TimestampUtc=[DateTimeOffset]::new([long]$item.TimestampUtc.UtcTicks,[TimeSpan]::Zero)
        }
    }
    $copy
}
